-- Growx Location
-- 02-initial-database-migration.sql
--
-- Target: Supabase PostgreSQL
-- Purpose: Create the V1 multi-tenant location schema with PostGIS.
--
-- IMPORTANT:
-- 1. Run this on a dedicated Supabase project for Growx Location.
-- 2. The public API must be the Cloudflare Worker, not direct browser access.
-- 3. Keep the Supabase secret/service-role credential only in the Worker.
-- 4. Normal location data lives in PostgreSQL/PostGIS, not Supabase Storage.

begin;

-- ---------------------------------------------------------------------------
-- 1. EXTENSIONS
-- ---------------------------------------------------------------------------

create schema if not exists extensions;

-- Supabase recommends installing PostGIS in the dedicated `extensions` schema.
create extension if not exists postgis with schema extensions;

-- Refuse to continue silently if PostGIS already exists in another schema.
do $$
declare
  postgis_schema text;
begin
  select n.nspname
    into postgis_schema
  from pg_extension e
  join pg_namespace n on n.oid = e.extnamespace
  where e.extname = 'postgis';

  if postgis_schema is distinct from 'extensions' then
    raise exception
      'PostGIS is installed in schema "%". Growx Location expects schema "extensions".',
      postgis_schema;
  end if;
end
$$;

-- ---------------------------------------------------------------------------
-- 2. COMMON UPDATED_AT TRIGGER
-- ---------------------------------------------------------------------------

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

revoke all on function public.set_updated_at() from public;
revoke all on function public.set_updated_at() from anon;
revoke all on function public.set_updated_at() from authenticated;

-- ---------------------------------------------------------------------------
-- 3. TENANTS
-- ---------------------------------------------------------------------------

create table public.tenants (
  id uuid primary key default gen_random_uuid(),

  name text not null,
  slug text not null unique,

  status text not null default 'active'
    check (status in ('active', 'suspended', 'archived')),

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint tenants_name_not_blank
    check (length(btrim(name)) > 0),

  constraint tenants_slug_format
    check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$')
);

create trigger tenants_set_updated_at
before update on public.tenants
for each row
execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- 4. API KEYS
-- ---------------------------------------------------------------------------

create table public.api_keys (
  id uuid primary key default gen_random_uuid(),

  tenant_id uuid not null
    references public.tenants(id)
    on delete cascade,

  name text not null,

  -- Example visible prefix: gx_loc_ab12
  key_prefix text not null,

  -- Store only a one-way SHA-256 (or stronger) hash generated by the Worker.
  -- Never store the raw API key.
  key_hash text not null unique,

  permissions jsonb not null default '["locations:read"]'::jsonb,

  status text not null default 'active'
    check (status in ('active', 'revoked')),

  expires_at timestamptz,
  last_used_at timestamptz,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint api_keys_name_not_blank
    check (length(btrim(name)) > 0),

  constraint api_keys_prefix_not_blank
    check (length(btrim(key_prefix)) > 0),

  constraint api_keys_hash_not_blank
    check (length(btrim(key_hash)) > 0),

  constraint api_keys_permissions_is_array
    check (jsonb_typeof(permissions) = 'array')
);

create index api_keys_tenant_id_idx
  on public.api_keys (tenant_id);

create index api_keys_active_prefix_idx
  on public.api_keys (key_prefix)
  where status = 'active';

create trigger api_keys_set_updated_at
before update on public.api_keys
for each row
execute function public.set_updated_at();

