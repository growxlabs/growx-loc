create index locations_location_type_id_idx
  on public.locations (location_type_id);

create index locations_tenant_status_idx
  on public.locations (tenant_id, status);

create index locations_tenant_city_idx
  on public.locations (tenant_id, city);

create index locations_tenant_state_idx
  on public.locations (tenant_id, state);

create index locations_tenant_pincode_idx
  on public.locations (tenant_id, pincode);

-- Spatial index used by nearby/radius queries.
create index locations_geo_point_gist_idx
  on public.locations
  using gist (geo_point);

-- ---------------------------------------------------------------------------
-- 7. SERVICE AREAS
-- ---------------------------------------------------------------------------

create table public.service_areas (
  id uuid primary key default gen_random_uuid(),

  tenant_id uuid not null
    references public.tenants(id)
    on delete cascade,

  location_id uuid
    references public.locations(id)
    on delete cascade,

  name text not null,

  area_type text not null
    check (area_type in ('radius', 'pincode_list', 'polygon')),

  -- Used only when area_type = 'radius'
  radius_km numeric(10, 3),

  -- Used only when area_type = 'pincode_list'
  pincodes text[],

  -- Reserved for polygon service areas.
  geometry extensions.geography(MultiPolygon, 4326),

  metadata jsonb not null default '{}'::jsonb,

  status text not null default 'active'
    check (status in ('active', 'inactive')),

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint service_areas_name_not_blank
    check (length(btrim(name)) > 0),

  constraint service_areas_metadata_is_object
    check (jsonb_typeof(metadata) = 'object'),

  constraint service_areas_shape_matches_type
    check (
      (
        area_type = 'radius'
        and location_id is not null
        and radius_km is not null
        and radius_km > 0
        and pincodes is null
        and geometry is null
      )
      or
      (
        area_type = 'pincode_list'
        and pincodes is not null
        and cardinality(pincodes) > 0
        and radius_km is null
        and geometry is null
      )
      or
      (
        area_type = 'polygon'
        and geometry is not null
        and radius_km is null
        and pincodes is null
      )
    )
);

create index service_areas_tenant_id_idx
  on public.service_areas (tenant_id);

create index service_areas_location_id_idx
  on public.service_areas (location_id);

create index service_areas_geometry_gist_idx
  on public.service_areas
  using gist (geometry)
  where geometry is not null;

create trigger service_areas_set_updated_at
before update on public.service_areas
for each row
execute function public.set_updated_at();

