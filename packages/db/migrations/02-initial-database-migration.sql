-- ---------------------------------------------------------------------------
-- 9. ROW LEVEL SECURITY + BACKEND-ONLY ACCESS
-- ---------------------------------------------------------------------------
--
-- Growx Location V1 is backend-only.
--
-- `anon` and `authenticated` receive NO table access.
-- The Cloudflare Worker uses a Supabase secret key / service-role credential
-- and performs tenant authorization before every query.
--
-- Supabase service_role bypasses RLS, so RLS here is defense-in-depth against
-- accidental future exposure via publishable/anon/authenticated credentials.

alter table public.tenants enable row level security;
alter table public.api_keys enable row level security;
alter table public.location_types enable row level security;
alter table public.locations enable row level security;
alter table public.service_areas enable row level security;
alter table public.location_sources enable row level security;

revoke all on table public.tenants from public, anon, authenticated;
revoke all on table public.api_keys from public, anon, authenticated;
revoke all on table public.location_types from public, anon, authenticated;
revoke all on table public.locations from public, anon, authenticated;
revoke all on table public.service_areas from public, anon, authenticated;
revoke all on table public.location_sources from public, anon, authenticated;

-- Explicit backend grants.
grant select, insert, update, delete
  on table public.tenants
  to service_role;

grant select, insert, update, delete
  on table public.api_keys
  to service_role;

grant select, insert, update, delete
  on table public.location_types
  to service_role;

grant select, insert, update, delete
  on table public.locations
  to service_role;

grant select, insert, update, delete
  on table public.service_areas
  to service_role;

grant select, insert, update, delete
  on table public.location_sources
  to service_role;

