-- ---------------------------------------------------------------------------
-- 6. LOCATIONS
-- ---------------------------------------------------------------------------

create table public.locations (
  id uuid primary key default gen_random_uuid(),

  tenant_id uuid not null
    references public.tenants(id)
    on delete cascade,

  location_type_id uuid not null
    references public.location_types(id)
    on delete restrict,

  name text not null,
  slug text not null,

  address_line_1 text,
  address_line_2 text,
  locality text,
  city text,
  district text,
  state text not null,
  pincode text,
  country_code char(2) not null default 'IN',

  latitude double precision not null,
  longitude double precision not null,

  -- Maintained automatically from latitude + longitude by trigger below.
  geo_point extensions.geography(Point, 4326) not null,

  phone text,
  whatsapp text,
  email text,
  website text,

  metadata jsonb not null default '{}'::jsonb,

  status text not null default 'active'
    check (status in ('active', 'inactive', 'draft')),

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint locations_name_not_blank
    check (length(btrim(name)) > 0),

  constraint locations_slug_format
    check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),

  constraint locations_tenant_slug_unique
    unique (tenant_id, slug),

  constraint locations_latitude_range
    check (latitude between -90 and 90),

  constraint locations_longitude_range
    check (longitude between -180 and 180),

  constraint locations_country_code_format
    check (country_code ~ '^[A-Z]{2}$'),

  constraint locations_metadata_is_object
    check (jsonb_typeof(metadata) = 'object')
);

-- Keep the PostGIS point synchronized with latitude/longitude.
create or replace function public.sync_location_geo_point()
returns trigger
language plpgsql
set search_path = pg_catalog, public, extensions
as $$
begin
  new.geo_point :=
    extensions.st_setsrid(
      extensions.st_makepoint(new.longitude, new.latitude),
      4326
    )::extensions.geography;

  return new;
end;
$$;

revoke all on function public.sync_location_geo_point() from public;
revoke all on function public.sync_location_geo_point() from anon;
revoke all on function public.sync_location_geo_point() from authenticated;

create trigger locations_sync_geo_point
before insert or update of latitude, longitude
on public.locations
for each row
execute function public.sync_location_geo_point();

create trigger locations_set_updated_at
before update on public.locations
for each row
execute function public.set_updated_at();

-- Tenant/filter indexes.
create index locations_tenant_id_idx
